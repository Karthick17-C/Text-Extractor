import base64
import os
import requests
from .models import OCRHistory

GEMINI_API_URL = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent"
DEFAULT_MODEL = "gemini-2.5-flash"


class OCRService:
    @staticmethod
    def extract_text_from_file(uploaded_file, model: str = DEFAULT_MODEL, instruction: str = None) -> tuple[str, str]:
        api_key = os.getenv("GEMINI_API_KEY")
        if not api_key:
            return None, "GEMINI_API_KEY not configured"

        if not instruction:
            instruction = "Extract all readable text from the image accurately."

        try:
            image_bytes = uploaded_file.read()
            image_b64 = base64.b64encode(image_bytes).decode("utf-8")
            content_type = getattr(uploaded_file, "content_type", None) or "image/jpeg"

            if "png" in content_type:
                mime_type = "image/png"
            elif "webp" in content_type:
                mime_type = "image/webp"
            elif "gif" in content_type:
                mime_type = "image/gif"
            else:
                mime_type = "image/jpeg"

            payload = {
                "contents": [
                    {
                        "parts": [
                            {"text": f"You are an expert OCR system. {instruction}"},
                            {
                                "inline_data": {
                                    "mime_type": mime_type,
                                    "data": image_b64
                                }
                            }
                        ]
                    }
                ]
            }

            url = f"{GEMINI_API_URL}?key={api_key}"
            headers = {"Content-Type": "application/json"}

            response = requests.post(url, headers=headers, json=payload, timeout=60)

            if response.status_code != 200:
                return None, f"Google Gemini API error ({response.status_code}): {response.text[:300]}"

            result = response.json()
            candidates = result.get("candidates", [])
            if not candidates:
                return None, "No OCR completion candidates returned by Google Gemini."

            parts = candidates[0].get("content", {}).get("parts", [])
            if not parts:
                return None, "No text generated by Google Gemini."

            extracted_text = parts[0].get("text", "").strip() or "No text detected."
            return extracted_text, None

        except (requests.RequestException, ValueError, Exception) as exc:
            return None, str(exc)

    @staticmethod
    def save_history(user, filename: str, extracted_text: str, model_used: str = DEFAULT_MODEL) -> OCRHistory:
        return OCRHistory.objects.create(
            user=user,
            filename=filename,
            extracted_text=extracted_text,
            model_used=model_used or DEFAULT_MODEL
        )
